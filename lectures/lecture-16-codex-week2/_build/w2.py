def pair(a, b):
    """이름표가 붙은 그림 두 장을 나란히 놓습니다. a, b = (이름표, 이미지, 대체 텍스트)

    발표용 덱에서는 split 두 칸에 넣습니다. Marp 에서는 세로로 긴 그림이 장표를 넘치므로
    높이를 정한 그림을 표의 두 칸에 넣습니다.
    """
    import sys
    if sys.modules['deck'].__name__ == 'marpdeck':
        cells = [pic(img, alt).strip().replace('![', '![h:380 ', 1) for _, img, alt in (a, b)]
        return ('| %s | %s |\n|:---:|:---:|\n| %s | %s |' % (a[0], b[0], cells[0], cells[1]))
    return split(*(pic(img, alt) + lines([(name, "")], tight=True) for name, img, alt in (a, b)))

