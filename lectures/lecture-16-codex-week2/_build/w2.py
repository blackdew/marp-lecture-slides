def row(*items):
    """이름표가 붙은 그림을 한 줄에 나란히 놓습니다. items = (이름표, 이미지, 대체 텍스트), 2장 또는 4장

    발표용 덱에서는 1주차의 split 을 씁니다. 4장은 split 안에 split 을 넣어서, 휴대폰에서는 한 줄씩 쌓입니다.
    Marp 에서는 세로로 긴 그림이 장표를 넘치므로 높이를 정한 그림을 표의 칸에 넣습니다.
    """
    import sys
    assert len(items) in (2, 4)
    if sys.modules['deck'].__name__ == 'marpdeck':
        h = 380 if len(items) == 2 else 250
        cells = [pic(img, alt).strip().replace('![', '![h:%d ' % h, 1) for _, img, alt in items]
        return ('| ' + ' | '.join(name for name, _, _ in items) + ' |\n|' + ':---:|' * len(items)
                + '\n| ' + ' | '.join(cells) + ' |')
    cols = [pic(img, alt) + lines([(name, "")], tight=True) for name, img, alt in items]
    if len(cols) == 2:
        return split(*cols)
    return split(split(cols[0], cols[1]), split(cols[2], cols[3]))


def pair(a, b):
    """그림 두 장을 나란히 놓습니다. row 와 같습니다."""
    return row(a, b)


